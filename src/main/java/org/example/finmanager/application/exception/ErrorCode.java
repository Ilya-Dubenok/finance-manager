package org.example.finmanager.application.exception;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/** Причина отказа выполнить команду или запустить приложение; несёт идентификатор сообщения. */
@Getter
@RequiredArgsConstructor
public enum ErrorCode {
  /** Пустое значение там, где оно обязательно. */
  EMPTY_VALUE("E-001"),
  /** Сумма не больше нуля. */
  AMOUNT_NOT_POSITIVE("E-004"),
  /** У суммы больше двух знаков после запятой. */
  AMOUNT_TOO_MANY_DECIMALS("E-005"),
  /** Сумма больше допустимой. */
  AMOUNT_TOO_LARGE("E-006"),
  /** Дата операции в будущем. */
  DATE_IN_FUTURE("E-008"),
  /** Начало периода позже его конца. */
  PERIOD_INVALID("E-009"),
  /** Значение длиннее допустимого. */
  VALUE_TOO_LONG("E-010"),
  /** В названии категории запятая или управляющий символ. */
  NAME_INVALID_CHARS("E-011"),
  /** В комментарии управляющий символ. */
  COMMENT_INVALID_CHARS("E-015"),
  /** Неверный логин или пароль. */
  INVALID_CREDENTIALS("B-101"),
  /** Получатель перевода не найден. */
  USER_NOT_FOUND("B-102"),
  /** Перевод самому себе. */
  SELF_TRANSFER("B-103"),
  /** Недостаточно средств для перевода. */
  INSUFFICIENT_FUNDS("B-104"),
  /** Категория не найдена. */
  CATEGORY_NOT_FOUND("B-105"),
  /** Категория с таким названием и типом уже есть. */
  CATEGORY_ALREADY_EXISTS("B-106"),
  /** Операция над системной категорией. */
  SYSTEM_CATEGORY("B-107"),
  /** Нельзя удалить категорию, по которой есть операции. */
  CATEGORY_HAS_OPERATIONS("B-108"),
  /** Бюджет можно задать только расходной категории. */
  BUDGET_FOR_INCOME_CATEGORY("B-109"),
  /** У категории нет бюджета. */
  BUDGET_NOT_FOUND("B-110"),
  /** Лимит бюджета не больше нуля. */
  BUDGET_LIMIT_NOT_POSITIVE("B-111"),
  /** Название категории совпадает со служебным словом. */
  RESERVED_NAME("B-112"),
  /** Снимок для импорта не проходит проверку. */
  IMPORT_INVALID("B-117"),
  /** Файл для экспорта не удалось записать. */
  EXPORT_FAILED("B-119"),
  /** Файл для импорта не найден или не читается. */
  IMPORT_READ_FAILED("B-120"),
  /** Файл уже существует; CLI превращает отказ в вопрос о перезаписи. */
  FILE_ALREADY_EXISTS("B-121"),
  /** Файл кошелька не читается или не проходит проверку. */
  WALLET_CORRUPTED("B-115"),
  /** Изменённые кошельки не удалось записать на диск. */
  SAVE_FAILED("B-116"),
  /** Файл пользователей не удалось прочитать или создать. */
  USERS_FILE_IO("S-001"),
  /** В строке файла пользователей нет знака равенства. */
  USERS_FILE_NO_SEPARATOR("S-002"),
  /** В файле пользователей недопустимый логин. */
  USERS_FILE_BAD_LOGIN("S-003"),
  /** В файле пользователей пустой пароль. */
  USERS_FILE_EMPTY_PASSWORD("S-004"),
  /** В файле пользователей логин повторяется. */
  USERS_FILE_DUPLICATE_LOGIN("S-005"),
  /** В файле пользователей нет ни одного пользователя. */
  USERS_FILE_NO_USERS("S-006");

  private final String catalogId;
}
